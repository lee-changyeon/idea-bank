-- 원장은 추가 전용: 지우기 금지, 순번·내용·해시 열 수정 금지 (공인 시각 열만 채울 수 있음)
CREATE OR REPLACE FUNCTION ib_events_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'events ledger is append-only';
  END IF;
  IF NEW.seq <> OLD.seq OR NEW.kind <> OLD.kind OR NEW.payload <> OLD.payload OR NEW.content_hash <> OLD.content_hash
     OR NEW.prev_hash <> OLD.prev_hash OR NEW.entry_hash <> OLD.entry_hash OR NEW.created_at <> OLD.created_at
     OR NEW.actor <> OLD.actor OR NEW.idea_seq IS DISTINCT FROM OLD.idea_seq THEN
    RAISE EXCEPTION 'events ledger rows are immutable (only tsa_* columns may change)';
  END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS ib_events_guard ON events;
CREATE TRIGGER ib_events_guard BEFORE UPDATE OR DELETE ON events FOR EACH ROW EXECUTE FUNCTION ib_events_guard();

-- Supabase 는 public 스키마를 REST API(anon 키)로 연다. 앱 서버만 postgres 역할로 접근하도록 막는다.
DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['users','admins','sessions','events','ideas','attachments','ndas','views','loans',
                           'contracts','settlements','audit','login_fails'] LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
      EXECUTE format('REVOKE ALL ON TABLE %I FROM anon, authenticated', t);
    END IF;
  END LOOP;
END $$;

-- 아이디어뱅크 온라인 — Postgres(Supabase) 스키마. SQLite 스키마(db.py SCHEMA)와 열 이름·뜻이 같다.
-- 첫 연결 때 PgDB._ensure_schema() 가 한 번 실행한다. 자세한 설명: web/DEPLOY_SUPABASE.md

CREATE TABLE IF NOT EXISTS users (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email      TEXT UNIQUE NOT NULL,
  name       TEXT NOT NULL,
  role       TEXT NOT NULL CHECK (role IN ('creator','business')),
  org        TEXT NOT NULL DEFAULT '',
  pw         TEXT NOT NULL,
  status     TEXT NOT NULL DEFAULT 'active',
  created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS admins (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username   TEXT UNIQUE NOT NULL,
  name       TEXT NOT NULL,
  pw         TEXT NOT NULL,
  created_at TEXT NOT NULL,
  pw_weak    INTEGER NOT NULL DEFAULT 0,
  totp_secret TEXT,
  totp_on    INTEGER NOT NULL DEFAULT 0,
  totp_last  INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS sessions (
  token_hash TEXT PRIMARY KEY,
  kind       TEXT NOT NULL CHECK (kind IN ('user','admin')),
  subject_id BIGINT NOT NULL,
  csrf       TEXT NOT NULL,
  created_at TEXT NOT NULL,
  expires_at DOUBLE PRECISION NOT NULL
);

-- 하나의 해시 체인 이벤트 원장. 추가 전용 (아래 트리거).
CREATE TABLE IF NOT EXISTS events (
  seq          BIGINT PRIMARY KEY,
  kind         TEXT NOT NULL,
  idea_seq     BIGINT,
  actor        TEXT NOT NULL,
  payload      BYTEA NOT NULL,
  content_hash TEXT NOT NULL,
  prev_hash    TEXT NOT NULL,
  entry_hash   TEXT NOT NULL,
  created_at   TEXT NOT NULL,
  tsa_url      TEXT,
  tsa_time     TEXT,
  tsa_token    BYTEA,
  tsa_error    TEXT,
  tsa_tries    INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS ix_ev_idea ON events(idea_seq);
CREATE INDEX IF NOT EXISTS ix_ev_hash ON events(content_hash);

CREATE TABLE IF NOT EXISTS ideas (
  seq          BIGINT PRIMARY KEY,
  idea_no      TEXT UNIQUE NOT NULL,
  owner_id     BIGINT NOT NULL,
  event_seq    BIGINT NOT NULL,
  parent_seq   BIGINT,
  root_seq     BIGINT NOT NULL,
  version      INTEGER NOT NULL,
  title        TEXT NOT NULL,
  body         TEXT NOT NULL,
  tags         TEXT NOT NULL,
  author       TEXT NOT NULL,
  canonical    BYTEA NOT NULL,
  content_hash TEXT NOT NULL,
  created_at   TEXT NOT NULL,
  disclosure   TEXT NOT NULL DEFAULT 'private' CHECK (disclosure IN ('private','summary','nda')),
  summary      TEXT NOT NULL DEFAULT '',
  hidden       INTEGER NOT NULL DEFAULT 0,
  hidden_reason TEXT
);
CREATE INDEX IF NOT EXISTS ix_ideas_hash ON ideas(content_hash);
CREATE INDEX IF NOT EXISTS ix_ideas_owner ON ideas(owner_id);
CREATE TABLE IF NOT EXISTS attachments (
  idea_seq BIGINT NOT NULL,
  name     TEXT NOT NULL,
  sha256   TEXT NOT NULL,
  size     BIGINT NOT NULL,
  mime     TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_att_sha ON attachments(sha256);
CREATE INDEX IF NOT EXISTS ix_att_idea ON attachments(idea_seq);

CREATE TABLE IF NOT EXISTS ndas (
